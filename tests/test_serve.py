import gzip
import io
from http.client import HTTPConnection
from pathlib import Path
import subprocess
import sys
import tempfile
from threading import Thread
import unittest
from unittest.mock import patch

from scripts.serve import GameHandler, make_server


class ServerTests(unittest.TestCase):
    def setUp(self):
        logger = patch.object(GameHandler, "log_message")
        logger.start()
        self.addCleanup(logger.stop)
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name) / "build"
        self.root.mkdir()
        (self.root / "index.html").write_text("<canvas></canvas>", encoding="utf-8")
        (self.root / "game.wasm").write_bytes(b"\0asm\x01\0\0\0")
        (self.root / "game.wasm.gz").write_bytes(gzip.compress(b"\0asm\x01\0\0\0"))
        # Header behavior only: valid Brotli is generated by the game's build tool.
        (self.root / "game.js.br").write_bytes(b"compressed-placeholder")
        (self.root / ".env").write_text("private", encoding="utf-8")
        self.server = make_server(self.root, port=0, isolate=True)
        self.thread = Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()
        self.addCleanup(self.stop)

    def stop(self):
        self.server.shutdown()
        self.server.server_close()
        self.thread.join(timeout=5)

    def request(self, path, method="GET", headers=None):
        connection = HTTPConnection("127.0.0.1", self.server.server_port, timeout=5)
        try:
            connection.request(method, path, headers=headers or {})
            response = connection.getresponse()
            return response.status, response.headers, response.read()
        finally:
            connection.close()

    def test_wasm_and_isolation_over_http(self):
        status, headers, body = self.request("/game.wasm")
        self.assertEqual(status, 200)
        self.assertEqual(body[:4], b"\0asm")
        self.assertEqual(headers["Content-Type"], "application/wasm")
        self.assertEqual(headers["Cross-Origin-Opener-Policy"], "same-origin")
        self.assertEqual(headers["Cross-Origin-Embedder-Policy"], "require-corp")
        self.assertEqual(headers["Cache-Control"], "no-store")

    def test_precompressed_resources_keep_underlying_mime(self):
        status, headers, body = self.request("/game.wasm.gz?version=1")
        self.assertEqual(status, 200)
        self.assertEqual(headers["Content-Type"], "application/wasm")
        self.assertEqual(headers["Content-Encoding"], "gzip")
        self.assertEqual(gzip.decompress(body)[:4], b"\0asm")
        status, headers, body = self.request("/game.js.br", "HEAD")
        self.assertEqual(status, 200)
        self.assertEqual(headers["Content-Encoding"], "br")
        self.assertEqual(headers["Content-Type"], "text/javascript")
        self.assertEqual(body, b"")
        status, headers, _ = self.request("/game.wasm%2egz")
        self.assertEqual(status, 200)
        self.assertEqual(headers["Content-Encoding"], "gzip")

    def test_single_ranges_open_ended_suffix_clamping_and_head(self):
        for value, expected in [('bytes=0-3',b'\0asm'), ('bytes=4-',b'\x01\0\0\0'),
                                ('bytes=-3',b'\0\0\0'), ('bytes=6-99',b'\0\0')]:
            status, headers, body = self.request('/game.wasm', headers={'Range':value})
            self.assertEqual(status,206)
            self.assertEqual(body,expected)
            self.assertEqual(int(headers['Content-Length']),len(expected))
            self.assertEqual(headers['Accept-Ranges'],'bytes')
            self.assertEqual(headers['Content-Type'],'application/wasm')
            self.assertEqual(headers['Cross-Origin-Embedder-Policy'],'require-corp')
        status, headers, body = self.request('/game.wasm','HEAD',{'Range':'bytes=0-3'})
        self.assertEqual(status,200)  # Range applies to GET only.
        self.assertEqual(headers['Content-Length'],'8')
        self.assertEqual(body,b'')

    def test_unsatisfiable_invalid_multiple_and_conditional_ranges(self):
        (self.root/'empty.dat').write_bytes(b'')
        for path,value in [('/game.wasm','bytes=8-'),('/game.wasm','bytes=-0'),('/empty.dat','bytes=0-')]:
            status,headers,body=self.request(path,headers={'Range':value})
            self.assertEqual(status,416)
            self.assertTrue(headers['Content-Range'].startswith('bytes */'))
            self.assertEqual(body,b'')
        for value in ['bytes=0-1,4-5','items=0-3','bytes=bad','bytes=-','x'*300]:
            self.assertEqual(self.request('/game.wasm',headers={'Range':value})[0],200)
        self.assertEqual(self.request('/game.wasm',headers={'Range':'bytes=0-1','If-Range':'unmatched'})[0],200)
        self.assertEqual(self.request('/%2eenv',headers={'Range':'bytes=0-1'})[0],403)

    def test_ranges_address_compressed_representation_and_preserve_encoding(self):
        original=(self.root/'game.wasm.gz').read_bytes()
        status,headers,body=self.request('/game.wasm.gz',headers={'Range':'bytes=0-3'})
        self.assertEqual(status,206)
        self.assertEqual(headers['Content-Encoding'],'gzip')
        self.assertEqual(body,original[:4])
        self.assertEqual(headers['Content-Range'],f'bytes 0-3/{len(original)}')

    def test_throttle_accounts_for_file_bytes_and_rejects_invalid_limits(self):
        handler=object.__new__(GameHandler)
        handler.throttle=100
        handler.byte_range=(0,19)
        target=io.BytesIO()
        with patch('scripts.serve.time.monotonic',return_value=0), patch('scripts.serve.time.sleep') as sleep:
            handler.copyfile(io.BytesIO(b'x'*30),target)
        self.assertEqual(target.getvalue(),b'x'*20)
        self.assertEqual([call.args[0] for call in sleep.call_args_list],[0.1,0.2])
        for invalid in [-1,float('inf'),float('nan')]:
            with self.assertRaises(ValueError):make_server(self.root,port=0,throttle=invalid)

    def test_compressed_404_is_not_mislabeled(self):
        status, headers, _ = self.request("/missing.wasm.gz")
        self.assertEqual(status, 404)
        self.assertNotIn("Content-Encoding", headers)

    def test_hidden_and_traversal_paths_are_refused(self):
        for path in ("/.env", "/%2eenv", "/../secret", "/%2e%2e/secret", "/x%5c..%5c.env", "/C:/secret", "/bad%00name"):
            with self.subTest(path=path):
                self.assertEqual(self.request(path)[0], 403)

    def test_directory_listing_disabled(self):
        (self.root / "empty").mkdir()
        self.assertEqual(self.request("/empty/")[0], 403)
        self.assertEqual(self.request("/")[0], 200)

    def test_symlink_file_and_index_refused(self):
        outside = self.root.parent / "outside.html"
        outside.write_text("private", encoding="utf-8")
        subdir = self.root / "subdir"
        subdir.mkdir()
        try:
            (self.root / "linked.html").symlink_to(outside)
            (subdir / "index.html").symlink_to(outside)
            (self.root / "linked-dir").symlink_to(self.root.parent, target_is_directory=True)
        except OSError:
            self.skipTest("symlink creation unavailable on this host")
        for path in ("/linked.html", "/subdir/", "/linked-dir/outside.html"):
            self.assertEqual(self.request(path)[0], 403)

    def test_loopback_and_optional_isolation(self):
        self.assertEqual(self.server.server_address[0], "127.0.0.1")
        self.stop()
        self.server = make_server(self.root, port=0, isolate=False)
        self.thread = Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()
        _, headers, _ = self.request("/")
        self.assertNotIn("Cross-Origin-Embedder-Policy", headers)

    def test_cli_errors_are_actionable(self):
        script = Path(__file__).resolve().parents[1] / "scripts" / "serve.py"
        for args in ([str(self.root / "missing")], [str(self.root), "--port", "-1"]):
            result = subprocess.run([sys.executable, str(script), *args], capture_output=True, text=True)
            self.assertEqual(result.returncode, 2)
            self.assertNotIn("Traceback", result.stderr)


if __name__ == "__main__":
    unittest.main()
